# -*- coding: utf-8 -*-
"""Модерация текста объявлений: мат и запрещённые темы.

Без внешних зависимостей. Проверка идёт по нормализованному тексту, чтобы ловить
обфускацию: латинские двойники букв (xyй), цифры вместо букв (х0й), разрядку
(«х у й», «х.у.й») и растянутые повторы (хуууй).

Основная функция — find_violation(text): возвращает (kind, fragment) или None.
"""
import os
import re

# --------------------------------------------------------------------------
# Нормализация
# --------------------------------------------------------------------------

# Латинские буквы, визуально совпадающие с кириллицей
_HOMOGLYPH = {
    'a': 'а', 'b': 'в', 'c': 'с', 'e': 'е', 'h': 'н', 'k': 'к', 'm': 'м',
    'o': 'о', 'p': 'р', 't': 'т', 'x': 'х', 'y': 'у', 'i': 'и', 'u': 'и',
}

# Цифры вместо букв — применяем только в токенах, где есть буквы,
# чтобы не портить цены и даты («5000 ₽» остаётся числом)
_DIGIT = {'0': 'о', '3': 'з', '4': 'ч', '6': 'б', '9': 'д', '1': 'и', '5': 'с'}

# Слова, которые попадают под корневые шаблоны, но безобидны
_ALLOW = ('себ', 'веб', 'хлеб', 'треб', 'потреб', 'ущерб', 'щеб', 'гребн')

_SPACED_RE = re.compile(
    r'(?:(?<![а-яёa-z])[а-яёa-z][\s.\-_*|]{1,2}){2,}[а-яёa-z](?![а-яёa-z])',
    re.IGNORECASE)

_TOKEN_RE = re.compile(r'[а-яёa-z0-9@$*#]+', re.IGNORECASE)
_REPEAT_RE = re.compile(r'(.)\1+')


def _glue_spaced(text):
    """«х у й» и «п.и.з.д.е.ц» склеивает в одно слово.

    Срабатывает только на цепочках одиночных букв — обычные слова не трогает.
    """
    def repl(m):
        return re.sub(r'[\s.\-_*|]+', '', m.group(0))
    return _SPACED_RE.sub(repl, text)


def _normalize(token):
    has_letter = any(ch.isalpha() for ch in token)
    out = []
    for ch in token:
        ch = _HOMOGLYPH.get(ch, ch)
        if has_letter:
            ch = _DIGIT.get(ch, ch)
        out.append(ch)
    s = ''.join(out).replace('ё', 'е')
    return _REPEAT_RE.sub(r'\1', s)


# --------------------------------------------------------------------------
# Шаблоны
# --------------------------------------------------------------------------

# Приставки, после которых корень остаётся матерным (заебал, выебон, напизделся)
_P = r'(?:на|за|вы|до|от|по|под|пере|при|раз|рас|про|недо|об|из|ни|о|у|в|с)?'

# Корни проверяются с начала слова — «страхуй» и «лебедь» не ложные срабатывания
_PROFANITY = [
    _P + r'[ъь]?ху[йеяи]',
    _P + r'[ъь]?пизд',
    _P + r'[ъь]?еб(?:а|у|и|о|л|н|е|ы|$)',
    _P + r'бляд',
    r'бля[дт]?$',
    r'сук[аиуео]$',
    r'сучк|сучар|сукин',
    r'муда[кч]|мудил|мудо[зн]',
    _P + r'хер(?:ня|ов|ак|ач|н[юя])',
    r'хер$',
    r'г[ао]ндон',
    r'залуп',
    r'дроч',
    r'манд[аы]$|мандав',
    r'пид[оеа]р|педик|педрил',
    r'шлюх',
    r'ублюд',
    r'гнид[аоыу]$',
    r'чмо$|чмош',
    r'долбо',
    r'мраз[ья]',
    r'сра[кнт]|обосра|засра',
    r'г[оа]вн',
    r'жоп[аоуые]$|жопн',
    r'дерьм',
    r'трах(?:ать|нуть|аль|ну)',
]

# Мат под звёздочками: х**, п***ц, бл**
# Мат под звёздочками: х**й, п**дец, бл**, с*ка. Маскирующий символ всегда
# идёт ПОСЛЕ буквы — поэтому «*только совершеннолетние» не считается матом.
_MASKED = [
    r'х[\*#@]+[йяею]',
    r'п[\*#@]+зд',
    r'п[\*#@]+д[ае]ц',
    r'бл[\*#@]{1,3}',
    r'[е]б[\*#@]{1,3}',
    r'с[\*#@]+к[аи]',
    r'муд[\*#@]+',
]

# Запрещённые темы. Формулировки узкие: «курьер» и «дропшиппинг» — легальные
# вакансии, под запрет попадают только однозначные маркеры.
_BANNED = [
    # наркотики
    r'закладк|закладок|закладчик|кладмен',
    r'мефедрон|амфетамин|метадон|гашиш|марихуан|кокаин|героин|экстази|мдма|спайс',
    r'наркотик|психотроп|курительн\w*\s+смес|гидропон',
    # интим
    r'интим\W*услуг|интим\s+за\s+деньг|эскорт|проститу|вебкам|индивидуалк',
    r'секс\s+за\s+деньг',
    # финансовые схемы
    r'обнал|отмыв\w*\s+денег|залив\w*\s+на\s+карт|дропповод|дроп\W*карт',
    # оружие
    r'взрывчат|боеприпас|тротил|оружи\w*\s+без\s+документ',
    # поддельные документы
    r'поддельн\w*\s+документ|купить\s+диплом|купить\s+справк|левы\w*\s+документ',
    # азартные игры
    r'казино|букмекер|ставки\s+на\s+спорт|1xbet',
    # пирамиды
    r'финансов\w*\s+пирамид|хайп\W*проект',
]


def _extra_banned():
    """Дополнительные запрещённые слова из переменной окружения BANNED_WORDS."""
    raw = os.environ.get('BANNED_WORDS', '')
    return [re.escape(w.strip().lower()) for w in raw.split(',') if w.strip()]


_PROFANITY_RX = [re.compile(p) for p in _PROFANITY]
_MASKED_RX = [re.compile(p, re.IGNORECASE) for p in _MASKED]
_BANNED_RX = [re.compile(p, re.IGNORECASE) for p in _BANNED]


# --------------------------------------------------------------------------
# Проверка
# --------------------------------------------------------------------------

def find_violation(*parts):
    """Ищет мат и запрещённые темы. Возвращает (kind, fragment) или None.

    kind: 'profanity' — мат, 'banned' — запрещённая тема.
    """
    text = ' '.join(str(p or '') for p in parts).lower()
    if not text.strip():
        return None

    for rx in _MASKED_RX:
        m = rx.search(text)
        if m:
            return ('profanity', m.group(0))

    tokens = _TOKEN_RE.findall(_glue_spaced(text))
    normalized = [_normalize(t) for t in tokens]

    for t in normalized:
        if t.startswith(_ALLOW):
            continue
        for rx in _PROFANITY_RX:
            if rx.match(t):
                return ('profanity', t)

    flat = ' '.join(normalized)
    for rx in _BANNED_RX + [re.compile(p) for p in _extra_banned()]:
        m = rx.search(flat)
        if m:
            return ('banned', m.group(0))
    return None


def reason_text(violation):
    """Человеко-понятная причина отказа для пользователя."""
    if not violation:
        return ''
    kind, fragment = violation
    if kind == 'profanity':
        return ('Объявление содержит нецензурную лексику («' + fragment +
                '»). Уберите её и отправьте снова.')
    return ('Объявление содержит запрещённую тему («' + fragment +
            '»). Такие вакансии в канале не публикуются.')
